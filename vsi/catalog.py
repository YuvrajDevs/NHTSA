"""Generate the data catalog: docs/catalog.md (for people) and site/catalog.json (for the project page).

Nothing is written by hand. For every table:
- description, owner, grain, PII tags         from contracts/*.yml
- columns and types, rows, version, updated   from the Delta table itself (schema + transaction log)
- quality                                     from the latest run in gold._quality_results
- lineage (upstream tables)                   parsed from sql/gold/*.sql; silver <- bronze <- NHTSA files
- metrics that use the table                  from metrics.yml
"""
import json
import re
from datetime import date

import yaml
from delta.tables import DeltaTable
from pyspark.sql import functions as F

from .config import OUT_DOCS, OUT_SITE, ROOT, table
from .gold import models
from .quality import load_contracts
from .sources import ALL
from .spark import get_spark


def lineage() -> dict[str, list[str]]:
    """table -> upstream tables."""
    up = {f"bronze.{s}": [f"nhtsa:{f}" for f in ALL[s].files] for s in ALL}
    for s in ALL:
        up[f"silver.{s}"] = [f"bronze.{s}"]
        up[f"silver.{s}_changes"] = [f"bronze.{s}", f"silver.{s}"]
    up["silver.recalls_history"] = ["silver.recalls_changes"]
    names = {n for n, _ in models()}
    for name, sql in models():
        sql_nc = re.sub(r"--[^\n]*", "", sql)
        refs = set(re.findall(r"\b(?:FROM|JOIN)\s+([a-z_][a-z0-9_]*)", sql_nc, flags=re.I))
        deps = []
        for r in sorted(refs):
            if r in ALL:
                deps.append(f"silver.{r}")
            elif r in names and r != name:
                deps.append(f"gold.{r}")
            elif r.startswith("seed_"):
                deps.append(f"seed.{r[5:]}")
        up[f"gold.{name}"] = deps
    up["gold.complaint_documents"] = ["silver.complaints"]
    return up


def build(load_date: str | None = None) -> dict:
    spark = get_spark()
    contracts = {c["table"]: c for c in load_contracts()}
    metrics = yaml.safe_load((ROOT / "metrics.yml").read_text())["metrics"]
    up = lineage()
    q = None
    qpath = table("gold", "_quality_results")
    if DeltaTable.isDeltaTable(spark, qpath):
        qd = spark.read.format("delta").load(qpath)
        last = qd.agg(F.max("run_date")).collect()[0][0]
        q = {r["table"]: (r["passed"], r["total"]) for r in qd.where(F.col("run_date") == last).groupBy("table").agg(
            F.sum(F.col("passed").cast("int")).alias("passed"), F.count("*").alias("total")).collect()}
    entries = []
    for full in sorted(up):
        layer, name = full.split(".", 1)
        path = table(layer, name)
        if not DeltaTable.isDeltaTable(spark, path):
            continue
        dt = DeltaTable.forPath(spark, path)
        hist = dt.history(1).collect()[0]
        df = spark.read.format("delta").load(path)
        c = contracts.get(full, {})
        col_specs = c.get("columns") or {}
        entries.append({
            "table": full, "layer": layer, "description": c.get("description", ""), "owner": c.get("owner", ""),
            "grain": c.get("grain", ""), "update": c.get("update", ""),
            "rows": df.count(), "version": hist["version"], "last_updated": str(hist["timestamp"]),
            "upstream": up.get(full, []), "downstream": sorted(t for t, ups in up.items() if full in ups),
            "quality": {"passed": q[full][0], "checks": q[full][1]} if q and full in q else None,
            "has_contract": bool(c),
            "metrics": [m["name"] for m in metrics if m["table"] == full],
            "columns": [{"name": f.name, "type": f.dataType.simpleString(),
                         "description": (col_specs.get(f.name) or {}).get("description", ""),
                         "pii": (col_specs.get(f.name) or {}).get("pii", "")}
                        for f in df.schema.fields],
        })
        print(f"catalog: {full} ({entries[-1]['rows']:,} rows)")
    out = {"generated_for": load_date or date.today().isoformat(), "tables": entries, "metrics": metrics}
    OUT_SITE.mkdir(parents=True, exist_ok=True)
    OUT_DOCS.mkdir(parents=True, exist_ok=True)
    (OUT_SITE / "catalog.json").write_text(json.dumps(out, default=str))
    write_markdown(out)
    return out


def write_markdown(cat: dict):
    L = ["# Data catalog", "",
         f"Generated by `python -m vsi.cli catalog` for load date {cat['generated_for']}. Do not edit by hand.", "",
         "## Lineage", "", "```mermaid", "flowchart LR"]
    ids = {}

    def nid(t):
        return ids.setdefault(t, f"n{len(ids)}")
    for e in cat["tables"]:
        for u in e["upstream"]:
            if u.startswith("seed.") or "_changes" in e["table"] or e["table"].endswith("_history"):
                continue
            L.append(f"    {nid(u)}[\"{u}\"] --> {nid(e['table'])}[\"{e['table']}\"]")
    L += ["```", "", "## Tables", "", "| Table | Grain | Rows | Owner | Quality |", "|---|---|---|---|---|"]
    for e in cat["tables"]:
        ql = f"{e['quality']['passed']}/{e['quality']['checks']}" if e["quality"] else "no contract"
        L.append(f"| [`{e['table']}`](#{e['table'].replace('.', '')}) | {e['grain']} | {e['rows']:,} | {e['owner']} | {ql} |")
    for e in cat["tables"]:
        L += ["", f"### {e['table']}", "", e["description"] or "_(no contract yet)_", "",
              f"- **Grain:** {e['grain'] or '-'}", f"- **Upstream:** {', '.join(e['upstream']) or '-'}",
              f"- **Downstream:** {', '.join(e['downstream']) or '-'}",
              f"- **Delta version:** {e['version']}, last updated {e['last_updated']}"]
        if e["metrics"]:
            L.append(f"- **Metrics defined on this table:** {', '.join(e['metrics'])}")
        pii = [c for c in e["columns"] if c["pii"]]
        if pii:
            L.append("- **Personal / sensitive data:** " + ", ".join(f"`{c['name']}` ({c['pii']})" for c in pii))
        described = [c for c in e["columns"] if c["description"]]
        if described:
            L += ["", "| Column | Type | Description |", "|---|---|---|"]
            L += [f"| `{c['name']}` | {c['type']} | {c['description']} |" for c in described]
    L += ["", "## Metrics", "", "| Metric | Definition | Table |", "|---|---|---|"]
    L += [f"| **{m['label']}** (`{m['name']}`) | `{m['sql']}`<br>{m.get('description', '')} | `{m['table']}` |" for m in cat["metrics"]]
    (OUT_DOCS / "catalog.md").write_text("\n".join(L) + "\n")
